def grab(path, t):
    """CAP_PROP_POS_MSEC 기준(가변 프레임레이트)."""
    cap = cv2.VideoCapture(path); last = None
    if 'h0' not in path:  # h0 영상은 탐색이 프레임을 못 돌려줘 처음부터 읽음
        cap.set(cv2.CAP_PROP_POS_MSEC, max(t - 1.5, 0) * 1000)
    while True:
        ok, f = cap.read()
        if not ok: return last
        last = f
        if cap.get(cv2.CAP_PROP_POS_MSEC) / 1000 >= t: return f


