/// T82: 이탈 **강도**(약함/심함)가 프레임마다 뒤집히는 것을 막는 래치.
///
/// 왜 필요한가 (2026-09-08, 사용자 실기기 보고):
///   "가만히 서 있어서 각도가 변하지 않아도 '크게 벗어남'과 '이탈'을 번갈아
///    가며, 그때마다 음성과 진동이 다시 나와 신뢰가 떨어진다."
///
///   원인은 두 곳이다. 둘 다 신뢰도를 **매 프레임 그대로** 임계값과 비교한다:
///     - 화면: `camera_screen.dart`의 `_severe` (색·문구·가장자리 펄스·굵기)
///     - 소리/진동: `feedback_service.dart`의 쿨다운 키가 (클래스, 강도) 쌍이라
///       강도가 뒤집히면 쿨다운을 무효화하고 **즉시 재발화**한다
///
/// 왜 히스테리시스가 아니라 시간 래치인가 (실측 근거):
///   같은 세션·5초 이내 연속쌍 46쌍 중 **11쌍(23.9%)** 에서 같은 방향인데도
///   강도가 뒤집혔고, 그 변화폭이 0.958->0.712, 0.982->0.684, 0.556->0.990처럼
///   **매우 크다**. 임계값 주변의 미세 진동이 아니므로 마진(히스테리시스)으로는
///   막히지 않는다 — 실제로 해제 임계값을 0.80->0.72로 낮춰도 23.9%->21.7%,
///   0.65까지 낮춰도 17.4%로 거의 그대로였다. 이건 T72에서 확인한 성질과 같다
///   ("경계에서 애매해 흔들리는 게 아니라 모델이 확신을 갖고 반대 답을 낸다").
///
///   그래서 값의 크기가 아니라 **지속 시간**을 본다: 바뀐 강도가 [dwell] 동안
///   유지되어야 비로소 바뀐 것으로 인정한다. 큰 폭으로 튀어도 곧 되돌아오면
///   보고값은 흔들리지 않는다.
///
/// 한계 (정직하게):
///   이 값이 실제로 발화 횟수를 얼마나 줄이는지는 **측정하지 못했다.** 보유한
///   사진은 간격이 약 2초인데 실기기는 약 0.17초마다 판정하므로, 사진으로는
///   실기기의 조밀한 판정 흐름을 재현할 수 없다. 위 23.9%는 "래치가 막아야 할
///   입력이 실제로 자주 들어온다"는 근거이지, 개선폭의 측정치가 아니다.
///   확인 방법: 실기기에서 가만히 선 채로 경고가 번갈아 나오는지 본다.
class SeverityLatch {
  SeverityLatch({this.dwell = const Duration(seconds: 2)});

  /// 바뀐 강도가 이 시간만큼 유지되어야 보고값을 바꾼다.
  ///
  /// 2초인 근거는 측정이 아니라 판단이다: 위 실측에서 강도가 뒤집힌 쌍의
  /// 촬영 간격이 2초 안팎이었으므로 그 정도 튐은 흡수하면서, 진짜로 악화됐을
  /// 때 알림이 2초 넘게 늦지는 않게 잡았다. 값을 바꾸려면 여기만 고치면 된다.
  final Duration dwell;

  bool _reported = false;
  bool? _pending;
  DateTime? _pendingSince;

  /// 지금 보고 중인 강도. [update] 없이 화면이 읽어도 안전하다.
  bool get isSevere => _reported;

  /// 새 관측값 [raw]를 넣고, **보고해야 할** 강도를 돌려준다.
  bool update(bool raw, DateTime now) {
    if (raw == _reported) {
      // 되돌아왔다 — 대기 중이던 변경은 없던 일로 한다.
      _pending = null;
      _pendingSince = null;
      return _reported;
    }
    if (_pending != raw) {
      _pending = raw;
      _pendingSince = now;
    }
    final since = _pendingSince;
    if (since != null && now.difference(since) >= dwell) {
      _reported = raw;
      _pending = null;
      _pendingSince = null;
    }
    return _reported;
  }

  /// 이탈이 끝났거나 방향이 바뀌면 호출한다 — 다음 이탈의 강도는 처음부터
  /// 다시 판단해야 한다(왼쪽에서 심했다고 오른쪽도 심한 것은 아니다).
  void reset() {
    _reported = false;
    _pending = null;
    _pendingSince = null;
  }
}
